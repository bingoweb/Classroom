'use strict';

const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');

const root = path.resolve(__dirname, '..');
const outputDirectory = path.join(root, 'public/vendor/liquidfun');

fs.mkdirSync(outputDirectory, { recursive: true });
esbuild.buildSync({
    entryPoints: [path.join(root, 'scripts/vendor/liquidfun-entry.mjs')],
    outfile: path.join(outputDirectory, 'liquidfun.module.js'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    legalComments: 'eof',
    banner: { js: '/* Local LiquidFun particle physics bundle — generated by npm run build:liquidfun-vendor. */' }
});

fs.copyFileSync(
    require.resolve('@box2d/particles/LICENSE'),
    path.join(outputDirectory, 'LICENSE')
);

fs.writeFileSync(
    path.join(outputDirectory, 'package.json'),
    `${JSON.stringify({ type: 'module' }, null, 2)}\n`
);
